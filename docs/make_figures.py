# ===== Fig 6: the scaling fault, on the public synthetic case =====
# tests/data/scaling_case.csv: 30 synthetic units, input x2 spanning 11.3
# decades.  References: the optimum in exact rational arithmetic and R's
# Benchmarking (tests/data/scaling_case_exact.csv, _benchmarking.csv).
from pleap.core.lp import envelopment
from pleap.core.scaling import column_scales, feasible
cd = pd.read_csv("tests/data/scaling_case.csv", float_precision="round_trip")
CX = cd[["x1", "x2"]].to_numpy(float); CY = cd[["y"]].to_numpy(float)
names = cd["dmu"].tolist()
exr = pd.read_csv("tests/data/scaling_case_exact.csv", float_precision="round_trip")
ber = pd.read_csv("tests/data/scaling_case_benchmarking.csv", float_precision="round_trip")
def ref(df, model, orient):
    sel = (df["model"] == model) & (df["orient"] == orient)
    return df.loc[sel, "efficiency"].to_numpy(float)
TOL = 1e-7
amx, amy = CX.mean(axis=0), CY.mean(axis=0)
gmx, gmy = column_scales(CX), column_scales(CY)

def one(k, sx, sy, model, orient, **kw):
    r = envelopment(CX[k] / sx, CY[k] / sy, CX / sx, CY / sy, model, orient, **kw)
    return r if r is None else (r[0] if orient == "input" else 1 / r[0], r[1])

f4 = {"n": len(CX), "x2_min": CX[:, 1].min(), "x2_max": CX[:, 1].max(),
      "decades": float(np.log10(CX[:, 1].max() / CX[:, 1].min())),
      "am": amx[1], "gm": gmx[1],
      "am_smallest": CX[:, 1].min() / amx[1], "gm_smallest": CX[:, 1].min() / gmx[1],
      "am_largest": CX[:, 1].max() / amx[1], "gm_largest": CX[:, 1].max() / gmx[1]}
# arithmetic-mean scaling, CCR input: one solve per unit, as v1.0.9-v1.1.0
e_ci = ref(exr, "CCR", "input")
am_ci = np.array([one(k, amx, amy, "CCR", "input")[0] for k in range(len(CX))])
gap = np.abs(am_ci - e_ci)
f4["am_ccr_in"] = {"wrong": int((gap > 1e-4).sum()), "max_gap": float(gap.max())}
for u in ("U18", "U03"):
    k = names.index(u); lam = one(k, amx, amy, "CCR", "input")[1]
    f4["am_ccr_in"][u] = {"exact": e_ci[k], "arith": am_ci[k],
                          "admissible": bool(feasible(CX[k], CY[k], CX, CY, lam,
                                                      am_ci[k], "CCR", "input"))}
# worst arithmetic-mean error over the four models
f4["am_max_gap_all"] = 0.0; f4["am_wrong_by_model"] = {}
for model in ("CCR", "BCC"):
    for orient in ("input", "output"):
        e = ref(exr, model, orient)
        v = np.array([one(k, amx, amy, model, orient)[0] for k in range(len(CX))])
        f4["am_wrong_by_model"][f"{model} {orient}"] = int((np.abs(v - e) > 1e-4).sum())
        f4["am_max_gap_all"] = max(f4["am_max_gap_all"], float(np.abs(v - e).max()))
# the dual check on the overstated unit (validation.md section 9)
k = names.index("U03")
n_, m_ = CX.shape
Ao = np.zeros((m_ + 1, n_ + 1)); bo = np.zeros(m_ + 1); co = np.zeros(n_ + 1); co[0] = 1
for i in range(m_):
    Ao[i, 0] = -CX[k, i]; Ao[i, 1:] = CX[:, i]
Ao[m_, 1:] = -CY[:, 0]; bo[m_] = -CY[k, 0]
from scipy.optimize import linprog
As = Ao.copy(); As[:m_, :] /= amx[:, None]; bs = bo.copy(); As[m_, :] /= amy[0]; bs[m_] /= amy[0]
rr = linprog(co, A_ub=As, b_ub=bs, bounds=[(0, None)] * (n_ + 1), method="highs")
yd = np.asarray(rr.ineqlin.marginals, float).copy(); yd[:m_] /= amx; yd[m_] /= amy[0]
f4["dual_U03_min_reduced_cost"] = float((co - Ao.T @ yd).min())
# the first form of the fix: geometric-mean and raw solves, best admissible
k = names.index("U20"); e_bi = ref(exr, "BCC", "input")
first = []
for sx, sy in ((gmx, gmy), (np.ones(2), np.ones(1))):
    r = one(k, sx, sy, "BCC", "input")
    if r is not None and feasible(CX[k], CY[k], CX, CY, r[1], r[0], "BCC", "input"):
        first.append(r[0])
f4["first_fix_U20_bcc_in"] = {"value": min(first), "exact": e_bi[k],
                              "own_peer_only": True}
# v1.12 and Benchmarking against the exact optimum
f4["v112_max_gap"] = 0.0; f4["bench_gap"] = {}
for model in ("CCR", "BCC"):
    for orient in ("input", "output"):
        e = ref(exr, model, orient)
        v = dea(CX, CY, model=model, orient=orient)["efficiency"]
        f4["v112_max_gap"] = max(f4["v112_max_gap"], float(np.abs(v - e).max()))
        g = np.abs(ref(ber, model, orient) - e)
        f4["bench_gap"][f"{model} {orient}"] = {"max": float(g.max()),
                                                "at": names[int(np.argmax(g))]}
# Table 3 of the paper: four units, exact optimum against each method
def two_solves(k, model, orient):
    got = []
    for sx, sy in ((gmx, gmy), (np.ones(2), np.ones(1))):
        r = envelopment(CX[k] / sx, CY[k] / sy, CX / sx, CY / sy, model, orient)
        if r is not None and feasible(CX[k], CY[k], CX, CY, r[1], r[0], model, orient):
            got.append(r[0])
    v = min(got) if orient == "input" else max(got)
    return v if orient == "input" else 1 / v
f4["table3"] = []
for u, model, orient in (("U18", "CCR", "input"), ("U03", "CCR", "input"),
                         ("U20", "BCC", "input"), ("U24", "BCC", "output")):
    k = names.index(u)
    f4["table3"].append({
        "label": f"{u}, {model} {orient}",
        "exact": ref(exr, model, orient)[k], "bench": ref(ber, model, orient)[k],
        "arith": one(k, amx, amy, model, orient)[0],
        "two": two_solves(k, model, orient),
        "v112": dea(CX, CY, model=model, orient=orient)["efficiency"][k]})
json.dump(f4, open(f"{OUT}/section4_facts.json", "w"), indent=1, default=float)
print(json.dumps(f4, indent=1, default=float))

