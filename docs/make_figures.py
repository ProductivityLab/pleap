# Simar-Wilson Algorithm 1, on the UNCORRECTED scores as the paper specifies:
# Algorithm 1 fixes the inference, Algorithm 2 would additionally correct the
# dependent variable.  Reported beside the naive truncated standard errors,
# because on this data set they turn out to agree, and saying so is more
# useful than implying the bootstrap rescued something.
from pleap.core.secondstage import (simarwilson_algorithm1,          # noqa: E402
                                    truncated_regression)
_sw = simarwilson_algorithm1(eff, Z, L=2000, seed=12345, names=["z1", "z2"])
_tr = truncated_regression(eff, Z, lower=None, upper=1.0, names=["z1", "z2"])
_se_naive = [float(v) for v in np.asarray(_tr["summary"].attrs["se_raw"],
                                          float)[:-1]]
facts["sw1"] = dict(
    coef=[round(float(v), 5) for v in _sw["summary"].attrs["coef_raw"]],
    boot_se=[round(float(v), 5) for v in _sw["summary"].attrs["se_raw"]],
    naive_se=[round(v, 5) for v in _se_naive],
    p=[round(float(v), 5) for v in _sw["summary"].attrs["p_raw"]],
    ci_low=[round(float(v), 5) for v in _sw["summary"].attrs["ci_low"]],
    ci_high=[round(float(v), 5) for v in _sw["summary"].attrs["ci_high"]],
    sigma=round(_sw["sigma"], 5), n=_sw["n"], L=_sw["L"])
_ratio = [b_ / a_ for b_, a_ in zip(facts["sw1"]["boot_se"], _se_naive)]
print(f"Simar-Wilson Algorithm 1: n={_sw['n']} inefficient units, "
      f"L={_sw['L']}, sigma={_sw['sigma']:.5f}")
print(f"  coefficients {facts['sw1']['coef']}")
print(f"  bootstrap SE {facts['sw1']['boot_se']}")
print(f"  naive SE     {facts['sw1']['naive_se']}")
print(f"  ratio boot/naive {[round(r_, 3) for r_ in _ratio]}")
gt = group_tests_param(b["boot_mean"], cs["Group"].to_numpy())
facts["anova"] = dict(test=gt["test"], stat=round(gt["stat"], 4), p=round(gt["p"], 5),
                      levene_p=round(gt["levene"]["p"], 4),
                      means=[round(v, 4) for v in gt["mean"]], n=list(gt["n"]))
json.dump(facts, open(f"{OUT}/section3_facts.json", "w"), indent=1, default=float)
print(json.dumps(facts, indent=1, default=float))

