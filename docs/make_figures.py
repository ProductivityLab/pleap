"""Regenerate every figure in the SoftwareX manuscript.

    python docs/make_figures.py

Writes docs/figures/fig1..fig6 (the numbers in the file names are the
manuscript's figure numbers), prints the numbers quoted in the paper and saves
them to docs/figures/section3_facts.json and section4_facts.json, so each can
be checked against the text.  Figures 1-5 come from examples/sample_data.xlsx,
the synthetic example that ships with PLEAP; Figure 6 from
tests/data/scaling_case.csv and its references (tests/test_scaling_reference.py).
All of it is generated by tests/data/make_synthetic_data.py; nothing comes from
real data.

Figure 1 needs the GUI dependencies (PyQt5).  Figure 5 is a screenshot of the
exported appendix taken with Node.js and Playwright (npm install playwright,
then npx playwright install chromium); without them the appendix is still
written and its path printed, so it can be opened and captured by hand.
Temporary files go to the system's temporary folder, on any OS.

The bootstrap takes a couple of minutes; the rest is seconds.
"""
import os, sys, json, tempfile, warnings
from pathlib import Path
warnings.filterwarnings("ignore")
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
# Render the window at 2x so Fig. 1 is not the one low-resolution figure in
# the paper: at 1180x800 it printed at roughly half the pixel density of the
# matplotlib figures beside it.  The layout is unchanged; only the device
# pixel ratio is.
os.environ.setdefault("QT_SCALE_FACTOR", "2")
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np, pandas as pd
sys.path.insert(0, "src")

