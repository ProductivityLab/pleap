OUT = "docs/figures"
TMP = Path(tempfile.mkdtemp(prefix="pleap_figures_"))
INS, OUTS = ["x1", "x2"], ["y1", "y2"]
d = pd.read_excel("examples/sample_data.xlsx")
cs = d[d.Period == d.Period.max()].reset_index(drop=True)
X = cs[INS].to_numpy(float); Y = cs[OUTS].to_numpy(float)
labels = cs["DMU_name"].tolist()
facts = {}

F.set_theme(palette="Colour-blind safe", style="Academic (white)", font_scale=1.05)

