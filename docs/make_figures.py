# ---------- Malmquist ----------
# The index is built from CRS distances and the efficiency change is split
# into PEC x SEC with the VRS distances, which is the Fare-Grosskopf-Norris-
# Zhang presentation and the convention in the applied literature.  Two
# consequences matter here: the scale component becomes visible, and the
# cross-period programs are always feasible, so no distance has to be
# substituted at all.
m = malmquist(d, "DMU_name", "Period", INS, OUTS, model="CCR", orient="input",
              scale_decomposition=True)
gm = lambda v: float(np.exp(np.log(v).mean()))
for t, g in m.groupby("t(Period)"):
    facts[f"mpi_{t}"] = dict(MI=gm(g["MI(t-1, t)"]), EC=gm(g["EC(t-1, t)"]),
                             TC=gm(g["TC(t-1, t)"]),
                             PEC=gm(g["PEC(t-1, t)"]), SEC=gm(g["SEC(t-1, t)"]),
                             up=int((g["MI(t-1, t)"] > 1).sum()), n=len(g))
facts["mpi_substitutions"] = dict(
    n=int(m.attrs["infeasible_substitutions"]),
    rows=int(m.attrs["rows_affected"]),
    of=int(m.attrs["cross_period_distances"]))
print("malmquist (CRS index, VRS scale split): "
      "{n} of {of} cross-period distances substituted".format(
          **facts["mpi_substitutions"]))
for t, f in sorted((k, v) for k, v in facts.items() if k.startswith("mpi_2")):
    print(f"  {t.split('_')[1]}: MI={f['MI']:.4f} EC={f['EC']:.4f} "
          f"TC={f['TC']:.4f} PEC={f['PEC']:.4f} SEC={f['SEC']:.4f}  "
          f"MI>1: {f['up']}/{f['n']}")

# The same panel under VRS, which is where the infeasible cross-period
# programs appear.  Section 3 reports this as the reason the index is
# computed under CRS, so the comparison is generated here rather than quoted
# from a one-off script.
mv = malmquist(d, "DMU_name", "Period", INS, OUTS, model="BCC", orient="input")
mv_omit = malmquist(d, "DMU_name", "Period", INS, OUTS, model="BCC",
                    orient="input", on_infeasible="omit")
facts["mpi_vrs_substitutions"] = dict(
    n=int(mv.attrs["infeasible_substitutions"]),
    rows=int(mv.attrs["rows_affected"]),
    of=int(mv.attrs["cross_period_distances"]))
for t, g in mv.groupby("t(Period)"):
    facts[f"vrs_{t}"] = dict(MI=gm(g["MI(t-1, t)"]),
                             up=int((g["MI(t-1, t)"] > 1).sum()), n=len(g))
for t, g in mv_omit.groupby("t(Period)"):
    g = g[g["MI(t-1, t)"].notna()]
    facts[f"vrs_{t}_omit"] = dict(MI=gm(g["MI(t-1, t)"]),
                                  up=int((g["MI(t-1, t)"] > 1).sum()), n=len(g))
print("under VRS: {n} of {of} substituted on {rows} rows".format(
    **facts["mpi_vrs_substitutions"]))
for _t in sorted({k.split("_")[1] for k in facts if k.startswith("vrs_2")}):
    _s, _o, _c = (facts.get(f"vrs_{_t}"), facts.get(f"vrs_{_t}_omit"),
                  facts.get(f"mpi_{_t}"))
    if _s and _o and _c:
        print(f"  {_t}: VRS substituted {_s['MI']:.4f} | VRS omitted "
              f"{_o['MI']:.4f} | CRS {_c['MI']:.4f}")
        if (_s["MI"] - 1.0) * (_c["MI"] - 1.0) < 0:
            print(f"       ^ the VRS substitution reverses the direction "
                  f"the CRS index reports for {_t}")

fig = F.fig_malm_quadrant(m, show_labels=False)
fig.savefig(f"{OUT}/fig4_malmquist.png", dpi=300, bbox_inches="tight"); plt.close(fig)
print("fig4")

